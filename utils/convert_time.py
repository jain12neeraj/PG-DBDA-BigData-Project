from datetime import datetime

def convert_list(name, timestamps):
    print("=" * 80)
    print(f"{name}")
    print("=" * 80)
    lis = []
    for ts in timestamps:
        dt = datetime.utcfromtimestamp(ts / 1000)
        lis.append(dt.strftime('%Y-%m-%d'))

    print(lis)
    print()


